#!/usr/bin/env node
// The eval history (T-05): fold the results an eval run left in artifacts/evals/results.jsonl
// into docs/evals-history.json (one row per set per run, newest last) and render
// docs/evals.md from it, so a prompt change that moves a number is visible as a line in
// a table rather than discovered by a customer.
//
//   node scripts/evals-history.mjs            fold the latest results in and render the page
//   node scripts/evals-history.mjs --render   render the page from the history alone
//   node scripts/evals-history.mjs --check    exit 1 if docs/evals.md is not what the history renders
//
// Plain JavaScript so it runs without a build.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const RESULTS = join(ROOT, 'artifacts', 'evals', 'results.jsonl');
const HISTORY = join(ROOT, 'docs', 'evals-history.json');
const PAGE = join(ROOT, 'docs', 'evals.md');
const KEEP = 60;

const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--render') ? 'render' : 'fold';

const history = existsSync(HISTORY) ? JSON.parse(readFileSync(HISTORY, 'utf8')) : { rows: [] };

if (mode === 'fold' && existsSync(RESULTS)) {
  const rows = readFileSync(RESULTS, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l));
  for (const r of rows) {
    // One row per set, mode and commit: a rerun of the same commit replaces its row.
    const i = history.rows.findIndex((h) => h.set === r.set && h.mode === r.mode && h.commit === r.commit);
    const row = {
      at: r.at,
      commit: r.commit,
      set: r.set,
      mode: r.mode,
      model: r.model ?? null,
      agreed: r.agreed,
      total: r.total,
      rate: Number(r.rate.toFixed(4)),
      threshold: r.threshold,
      passed: r.passed,
    };
    if (i >= 0) history.rows[i] = row;
    else history.rows.push(row);
  }
  history.rows.sort((a, b) => a.at.localeCompare(b.at));
  // Keep the last KEEP rows per set and mode.
  const kept = [];
  for (const set of new Set(history.rows.map((r) => r.set))) {
    for (const m of ['pipeline', 'model']) {
      kept.push(...history.rows.filter((r) => r.set === set && r.mode === m).slice(-KEEP));
    }
  }
  history.rows = kept.sort((a, b) => a.at.localeCompare(b.at));
  writeFileSync(HISTORY, JSON.stringify(history, null, 2) + '\n');
}

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const lines = [];
lines.push('# Eval results over time');
lines.push('');
lines.push(
  'Generated by `scripts/evals-history.mjs` from `docs/evals-history.json`, which CI folds the latest `artifacts/evals/results.jsonl` into. Each set is measured two ways: the pipeline against the labels (a stub model that answers exactly what the labels say, proving the plumbing) and, when a self-hosted model is configured, the model against the labels. The threshold is the share that must agree before a prompt change may ship; a row below it is a red build.',
);
lines.push('');
const sets = [...new Set(history.rows.map((r) => r.set))].sort();
if (sets.length === 0) {
  lines.push('_No results recorded yet._');
}
for (const set of sets) {
  lines.push(`## ${set}`);
  lines.push('');
  lines.push('| When | Commit | Mode | Model | Agreed | Rate | Threshold | Result |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of history.rows.filter((r) => r.set === set).slice().reverse()) {
    lines.push(
      `| ${r.at.slice(0, 10)} | ${r.commit} | ${r.mode} | ${r.model ?? '—'} | ${r.agreed}/${r.total} | ${pct(r.rate)} | ≥ ${pct(r.threshold)} | ${r.passed ? 'pass' : 'FAIL'} |`,
    );
  }
  lines.push('');
}
const rendered = lines.join('\n');

if (mode === 'check') {
  const current = existsSync(PAGE) ? readFileSync(PAGE, 'utf8') : '';
  if (current !== rendered) {
    console.error('docs/evals.md is stale; run node scripts/evals-history.mjs --render');
    process.exit(1);
  }
  console.log('docs/evals.md is current');
} else {
  writeFileSync(PAGE, rendered);
  console.log(`docs/evals.md: ${history.rows.length} row(s) over ${sets.length} set(s)`);
}
